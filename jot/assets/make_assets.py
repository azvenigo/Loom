"""Regenerate jot/CaptureAssets.h from the files beside this script.

    icon-180.png   the Home Screen icon, spliced into the page as a data: URI. Rendered from icon.svg:
                   inkscape icon.svg --export-type=png --export-filename=icon-180.png --export-width=180
    graphite.jpg   the Instrument studies' graphite scan (CC0, ambientCG), 1024px, untouched - its
                   faint blue cast is part of the look. Too big to inline in a page that is never
                   cached, so jot serves it as GET /jot/a/graphite.jpg and the phone caches it.
                   Changing it means renaming the route too, or phones keep the old one for a month.

    python3 jot/assets/make_assets.py
"""
import base64
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "CaptureAssets.h")
CHUNK = 120   # one literal per line; well under any compiler's literal limit


def literal(name, path):
    with open(os.path.join(HERE, path), "rb") as f:
        b = base64.b64encode(f.read()).decode()
    lines = ['    "%s"' % b[i:i + CHUNK] for i in range(0, len(b), CHUNK)]
    return "inline const char* %s()\n{\n    return\n%s;\n}\n" % (name, "\n".join(lines))


with open(OUT, "w", newline="\n") as f:
    f.write("#pragma once\n// Copyright (c) 2026 Alexander Zvenigorodsky. MIT License. See LICENSE.\n"
            "// GENERATED by jot/assets/make_assets.py - edit the assets, not this file.\n"
            "// Base64. The icon is spliced into the capture page as a data: URI; the graphite is decoded\n"
            "// once and served as GET /jot/a/graphite.jpg (jot/CapturePage.h).\n\n")
    f.write(literal("JotIconPngBase64", "icon-180.png") + "\n")
    f.write(literal("JotGraphiteJpgBase64", "graphite.jpg"))
print("wrote", os.path.normpath(OUT))
